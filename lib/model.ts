// The token radar's valuation model: a sealed DefiLlama snapshot in, a ranked board out.
//
// The board ranks every protocol the snapshot records as pre-token and rankable: the whole
// watchlist (the floor) plus every rankable pre-token protocol below the floor, by TVL. Nothing
// is hand-picked and no protocol name is ever special-cased; the same function scores every row,
// and every constant the function uses is either fixed here or computed from the snapshot itself.
//
// Implied value is a comparables valuation, not a flat multiple. A protocol that has not launched
// a token yet is worth what the market pays for the same kind of business that already trades:
// for each category, the multiple is the median market-cap-to-TVL of the live-token protocols in
// that category, read from this very snapshot. A category with too few live comparables falls back
// to the global median, and every multiple is clamped to a sane band so one outlier cannot set the
// price. The rest is the house shape: seven-day growth, damped, and maturity from how long the
// protocol has run with no token.
//
//   multiple     = median(mcap_usd / tvl_usd) over live-token protocols in the category
//                  (n >= 3, else the global median), clamped to [MULT_MIN, MULT_MAX]
//   growth       = clamp(change_7d, GROWTH_FLOOR, GROWTH_CAP) per cent
//   growthMult   = 1 + (growth / 100) * GROWTH_WEIGHT
//   maturity     = MATURITY_FLOOR + min(age_days, MATURITY_DAYS) / MATURITY_DAYS * MATURITY_RANGE
//                  (age_days unknown: UNKNOWN_AGE_DAYS)
//   implied      = max(1, round(tvl_usd * multiple * growthMult * maturity))
//
// The dashboard states this model in full, with the multiples table, so a reader can check any row.

/** One protocol as the sealed snapshot records it: exactly its ten fields. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole sealed snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's fixed constants. The multiples are computed, never fixed here. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  multiple_min: number;
  multiple_max: number;
  multiple_min_comps: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  multiple_min: 0.1,
  multiple_max: 0.6,
  multiple_min_comps: 3,
};

